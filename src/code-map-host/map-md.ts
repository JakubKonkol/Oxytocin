import { posix } from 'node:path';
import type { CodeMapGraph } from '@shared/domain/code-map';
import { comparePaths } from './enumerate';
import type { ProjectConfig } from './resolve/config';
import { sha256 } from './store/writer';

import { CODE_MAP_AGENT_INSTRUCTIONS } from '@shared/domain/code-map';
export { CODE_MAP_AGENT_INSTRUCTIONS } from '@shared/domain/code-map';
export function entryPoints(graph: CodeMapGraph, configs: ReadonlyMap<string, ProjectConfig>): string[] {
  const paths = new Set(graph.files.map((file) => file.path));
  const entries = new Set<string>();
  for (const [path, config] of configs) {
    if (config.kind !== 'package') continue;
    const bins = typeof config.data.bin === 'string' ? [config.data.bin] : Object.values(config.data.bin ?? {});
    for (const entry of [config.data.main, config.data.types, ...bins])
      if (entry) {
        const candidate = posix.normalize(posix.join(posix.dirname(path), entry));
        if (paths.has(candidate)) entries.add(candidate);
      }
  }
  for (const file of graph.files) if (file.test) entries.add(file.path);
  return [...entries].sort(comparePaths);
}
function safe(text: string): string {
  return text.replace(/[\r\n]/g, ' ');
}
function inline(text: string): string {
  text = safe(text);
  const delimiter = '`'.repeat(Math.max(0, ...(text.match(/`+/g) ?? []).map((value) => value.length)) + 1);
  return `${delimiter} ${text} ${delimiter}`;
}
const countFiles = (count: number) => `${count} ${count === 1 ? 'file' : 'files'}`;
function boundedLines(lines: string[], budget: number): string[] {
  const result: string[] = [];
  let bytes = 0;
  for (let index = 0; index < lines.length; index++) {
    const line = lines[index]!;
    const marker = `… ${lines.length - index} more (use oxy_repo_map with pathPrefix)`;
    if (bytes + Buffer.byteLength(line) + 1 + Buffer.byteLength(marker) + 1 > budget) {
      if (bytes + Buffer.byteLength(marker) + 1 <= budget) result.push(marker);
      break;
    }
    result.push(line);
    bytes += Buffer.byteLength(line) + 1;
  }
  return result;
}

export function renderMapMarkdown(
  graph: CodeMapGraph,
  configs: ReadonlyMap<string, ProjectConfig> = new Map(),
  maxBytes = 32 * 1024,
): string {
  const graphHash = sha256(`${JSON.stringify(graph)}\n`);
  const scale = Math.min(1, maxBytes / (32 * 1024));
  const languageCounts = new Map<string, Map<string, number>>();
  for (const file of graph.files)
    for (let path = posix.dirname(file.path); ; path = posix.dirname(path)) {
      const counts = languageCounts.get(path) ?? new Map<string, number>();
      counts.set(file.language, (counts.get(file.language) ?? 0) + 1);
      languageCounts.set(path, counts);
      if (path === '.') break;
    }
  const lines = [
    '# Code Map',
    '',
    'Generated by Oxytocin Code Map. Do not edit.',
    `Graph SHA-256: ${graphHash}`,
    '',
    CODE_MAP_AGENT_INSTRUCTIONS,
    '',
    `Coverage: ${graph.coverage.files.indexed} indexed, ${graph.coverage.files.unsupported} file-only, ${graph.coverage.files.failed} failed, ${graph.coverage.files.skipped} skipped entries.`,
    'Calls and potential dependents in indexed code are not exhaustive.',
    '',
    '## Layout',
    '',
  ];
  lines.push(
    ...boundedLines(
      graph.groups.map(
        (group) =>
          `${'  '.repeat(group.path === '.' ? 0 : group.path.split('/').length)}- ${inline(`${group.path}/`)} — ${countFiles(group.files)} · ${[...(languageCounts.get(group.path) ?? [])].sort(([left, a], [right, b]) => b - a || comparePaths(left, right))[0]?.[0] ?? 'unknown'}${/(^|\/)(__tests__|tests?|spec)(\/|$)/.test(group.path) ? ' (tests)' : ''}`,
      ),
      8192 * scale,
    ),
  );
  const entries = entryPoints(graph, configs);
  lines.push(
    '',
    '## Entry points',
    '',
    ...boundedLines(
      entries.map((path) => `- ${inline(path)}`),
      2048 * scale,
    ),
  );
  const counts = new Map<string, Set<string>>();
  for (const edge of graph.edges)
    if (['imports', 'exports'].includes(edge.rel) && edge.to.startsWith('f:')) {
      const importers = counts.get(edge.to) ?? new Set<string>();
      importers.add(edge.from);
      counts.set(edge.to, importers);
    }
  const hubs = [...counts].sort(([left, a], [right, b]) => b.size - a.size || comparePaths(left, right)).slice(0, 30);
  lines.push(
    '',
    '## Hubs',
    '',
    ...boundedLines(
      hubs.map(
        ([id, importers]) =>
          `- ${inline(id.slice(2))} — ${importers.size} importing ${importers.size === 1 ? 'file' : 'files'}`,
      ),
      4096 * scale,
    ),
  );
  lines.push('', '## Public API', '');
  const byFile = new Map<string, typeof graph.symbols>();
  for (const symbol of graph.symbols)
    if (symbol.exported) {
      const list = byFile.get(symbol.file) ?? [];
      list.push(symbol);
      byFile.set(symbol.file, list);
    }
  const apiLines: string[] = [];
  const candidates = [
    ...new Set([
      ...hubs.map(([id]) => id.slice(2)),
      ...entries,
      ...[...byFile.keys()].sort(comparePaths).map((id) => id.slice(2)),
    ]),
  ].filter((path) => byFile.has(`f:${path}`));
  for (const path of candidates.slice(0, 100)) {
    const symbols = byFile.get(`f:${path}`) ?? [];
    if (symbols.length)
      apiLines.push(
        `### ${inline(path)}`,
        '',
        ...symbols
          .slice(0, 30)
          .map(
            (symbol) =>
              `- ${inline(symbol.signature)} (${symbol.span[0]}:${symbol.span[1]})${symbol.stale ? ' — stale' : ''}`,
          ),
        '',
      );
    if (symbols.length > 30) apiLines.push(`… ${symbols.length - 30} more (use oxy_file_outline)`);
  }
  if (candidates.length > 100)
    apiLines.push(`… ${candidates.length - 100} more API files (use oxy_repo_map with pathPrefix)`);
  lines.push(...boundedLines(apiLines, 12_288 * scale));
  lines.push('## Coverage notes', '');
  for (const [language, count] of Object.entries(graph.coverage.byLanguage))
    lines.push(
      `- ${safe(language)}: ${count} files; ${['typescript', 'javascript'].includes(language) ? 'Calls (syntax and lexical bindings; unknown receivers remain unresolved)' : 'Files'}.`,
    );
  lines.push(
    `- ${graph.coverage.unresolved.imports} unresolved imports; ${graph.coverage.unresolved.calls} unresolved calls.`,
    '- Excluded directories are skipped without enumerating their contents.',
    '',
  );
  const output: string[] = [];
  let bytes = 0;
  for (let index = 0; index < lines.length; index++) {
    const line = `${lines[index]!}\n`;
    const marker = `… ${lines.length - index} more (use oxy_repo_map with pathPrefix)\n`;
    if (bytes + Buffer.byteLength(line) + Buffer.byteLength(marker) > maxBytes) {
      if (bytes + Buffer.byteLength(marker) <= maxBytes) output.push(marker);
      break;
    }
    output.push(line);
    bytes += Buffer.byteLength(line);
  }
  return output.join('');
}
